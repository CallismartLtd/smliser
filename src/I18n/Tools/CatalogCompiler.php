declare( strict_types = 1 );

namespace SmartLicenseServer\I18n\Tools;

use SmartLicenseServer\I18n\Catalog;
use SmartLicenseServer\I18n\I18nException;
use SmartLicenseServer\I18n\Po\PoDocument;
use SmartLicenseServer\I18n\Po\PoEntry;

/**
 * Compiles PO files into the runtime formats:
 *
 * - `{domain}-{locale}.l10n.php` — every string; fastest to load (OPcache)
 *   and also read natively by WordPress 6.5+.
 * - `{domain}-{locale}.mo` — every string; for WordPress before 6.5 and
 *   other gettext tools.
 * - `{domain}-js-{locale}.l10n.php` — only the strings used by JavaScript,
 *   so pages ship a small payload to the browser.
 */
final class CatalogCompiler {

	/**
	 * Compile a PO file next to itself.
	 *
	 * @param string $po_path Path to `{domain}-{locale}.po`.
	 * @return array<int, string> Paths written.
	 * @throws I18nException
	 */
	public function compile( string $po_path ) : array {
		if ( ! preg_match( '/^(.+)-([A-Za-z0-9_]+)\.po$/', basename( $po_path ), $m ) ) {
			throw new I18nException( sprintf( '"%s" is not named {domain}-{locale}.po.', $po_path ) );
		}

		[ , $domain, $locale ] = $m;

		$dir      = dirname( $po_path );
		$document = PoDocument::from_file( $po_path );
		$written  = [];

		$php = sprintf( '%s/%s-%s.l10n.php', $dir, $domain, $locale );
		$this->write( $php, $this->to_php( $document, $domain, $locale, basename( $po_path ) ) );
		$written[] = $php;

		$mo = sprintf( '%s/%s-%s.mo', $dir, $domain, $locale );
		$this->write( $mo, $this->to_mo( $document ) );
		$written[] = $mo;

		$js_entries = array_filter(
			$document->entries,
			static fn ( PoEntry $entry ) : bool => [] !== array_filter( $entry->references, static fn ( string $ref ) : bool => (bool) preg_match( '/\.js:\d+$/', $ref ) )
		);

		$js_path = sprintf( '%s/%s-js-%s.l10n.php', $dir, $domain, $locale );

		if ( [] !== $js_entries ) {
			$this->write( $js_path, $this->to_php( new PoDocument( $document->headers, $js_entries ), $domain . '-js', $locale, basename( $po_path ) ) );
			$written[] = $js_path;
		} elseif ( is_file( $js_path ) ) {
			@unlink( $js_path );
		}

		return $written;
	}

	/**
	 * Build a `.l10n.php` file body.
	 */
	public function to_php( PoDocument $document, string $domain, string $locale, string $source = '' ) : string {
		$catalog  = $document->to_catalog();
		$messages = [];

		foreach ( $catalog->entries() as $key => $forms ) {
			$messages[ $key ] = implode( "\0", $forms );
		}

		$data = [
			'domain'       => $domain,
			'language'     => $catalog->header( 'Language' ) ?? $locale,
			'plural-forms' => $catalog->plural_forms()->header(),
			'messages'     => $messages,
		];

		$source = '' === $source ? "{$domain}-{$locale}.po" : $source;
		$source = (string) preg_replace( '/[^A-Za-z0-9_.-]/', '', $source );

		return "<?php\n// Generated by `smliser i18n compile` from {$source}. Do not edit.\nreturn " . $this->export( $data ) . ";\n";
	}

	/**
	 * Export an array as short-syntax PHP, escaping control characters.
	 */
	private function export( array $data, int $level = 0 ) : string {
		$pad   = str_repeat( "\t", $level + 1 );
		$lines = [];

		foreach ( $data as $key => $value ) {
			$value   = is_array( $value ) ? $this->export( $value, $level + 1 ) : $this->literal( (string) $value );
			$lines[] = $pad . $this->literal( (string) $key ) . ' => ' . $value . ',';
		}

		return "[\n" . implode( "\n", $lines ) . "\n" . str_repeat( "\t", $level ) . ']';
	}

	/**
	 * A PHP string literal. Strings with control characters use double
	 * quotes with escapes; everything else single quotes.
	 */
	private function literal( string $value ) : string {
		if ( ! preg_match( '/[\x00-\x1F\x7F]/', $value ) ) {
			return "'" . strtr( $value, [ '\\' => '\\\\', "'" => "\\'" ] ) . "'";
		}

		$escaped = preg_replace_callback(
			'/[\x00-\x1F\x7F"\\\\$]/',
			static fn ( array $m ) : string => match ( $m[0] ) {
				"\n"    => '\\n',
				"\t"    => '\\t',
				"\r"    => '\\r',
				'"'     => '\\"',
				'\\'    => '\\\\',
				'$'     => '\\$',
				default => sprintf( '\\x%02X', ord( $m[0] ) ),
			},
			$value
		);

		return '"' . $escaped . '"';
	}

	/**
	 * Build binary MO data.
	 */
	public function to_mo( PoDocument $document ) : string {
		$strings = [];

		$header = '';
		foreach ( $document->headers as $name => $value ) {
			$header .= $name . ': ' . $value . "\n";
		}
		$strings[''] = $header;

		foreach ( $document->entries as $entry ) {
			if ( $entry->is_fuzzy() || '' === implode( '', $entry->translations ) ) {
				continue;
			}

			$original = Catalog::key( $entry->msgid, $entry->context );

			if ( null !== $entry->plural ) {
				$original .= "\0" . $entry->plural;
			}

			$strings[ $original ] = implode( "\0", $entry->translations );
		}

		ksort( $strings, SORT_STRING );

		$count       = count( $strings );
		$table_start = 28;
		$data_start  = $table_start + $count * 16;
		$originals   = '';
		$translated  = '';
		$o_table     = '';
		$t_table     = '';

		foreach ( array_keys( $strings ) as $original ) {
			$o_table   .= pack( 'VV', strlen( (string) $original ), $data_start + strlen( $originals ) );
			$originals .= $original . "\0";
		}

		$t_start = $data_start + strlen( $originals );

		foreach ( $strings as $translation ) {
			$t_table    .= pack( 'VV', strlen( $translation ), $t_start + strlen( $translated ) );
			$translated .= $translation . "\0";
		}

		return pack( 'V7', 0x950412de, 0, $count, $table_start, $table_start + $count * 8, 0, $data_start )
			. $o_table . $t_table . $originals . $translated;
	}

	/**
	 * Write a file atomically.
	 */
	private function write( string $path, string $contents ) : void {
		$tmp = $path . '.' . bin2hex( random_bytes( 4 ) ) . '.tmp';

		if ( false === file_put_contents( $tmp, $contents ) || ! rename( $tmp, $path ) ) {
			@unlink( $tmp );
			throw new I18nException( sprintf( 'Cannot write "%s".', $path ) );
		}

		if ( function_exists( 'opcache_invalidate' ) && str_ends_with( $path, '.php' ) ) {
			@opcache_invalidate( $path, true );
		}
	}
}
